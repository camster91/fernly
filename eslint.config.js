// ESLint 9 flat config for Fernly.
//
// Inherits the React Native + TypeScript preset from @react-native, then
// layers repo-specific overrides on top. The goal is to catch the issues
// the comprehensive repo review (issue #1) found:
//   - `react-hooks/exhaustive-deps` (5 screens have missing dep arrays)
//   - no-unused-vars / no-unused-imports (multiple dead imports)
//   - bare hex literals outside the theme tokens (locked-contract pattern)
//
// v0.2 additions:
//   - Tolerates the unversioned `scripts/test-crisis.mjs` import path
//     (../src/safety/crisis.ts) since the test runs via tsx, not via
//     the bundled RN runtime.
//   - Marks `src/theme.ts` as the canonical home for hex literals —
//     every other file must import from `colors.*`.

const reactNativeConfig = require('@react-native/eslint-config/flat');

module.exports = [
  // Ignore patterns
  {
    ignores: [
      'node_modules/**',
      '.expo/**',
      'dist/**',
      'web-build/**',
      // Generated by Expo — never lint
      'expo-env.d.ts',
      'ios/**',
      'android/**',
      // Self-lint: ESLint can't parse its own config file with the
      // Babel parser (it has no .babelrc). Skip it.
      'eslint.config.js',
    ],
  },

  // Pull in the React Native + TypeScript preset
  ...reactNativeConfig,

  // Repo-specific overrides
  {
    files: ['**/*.ts', '**/*.tsx'],
    rules: {
      // The locked theme contract: no hex literals outside theme.ts.
      // src/theme.ts is the canonical home — see exclusion in the next block.
      // Note: pre-existing violations in PracticeScreen.tsx:15-16 are
      // fixed in PR #4 (hex literals → theme tokens). This rule will
      // catch any future regression once PR #4 lands.
      'no-restricted-syntax': [
        'error',
        {
          selector: 'Literal[value=/^#[0-9A-Fa-f]{6}$/]',
          message: 'Use colors.* from src/theme.ts. Bare hex literals are not allowed in src/.',
        },
      ],
    },
  },

  // PRACTICE SCREEN EXCLUSION — pre-PR-#4 contains two hex literals at
  // lines 15-16. PR #4 (chore: asset path fix, dead deps, hex literals
  // → theme tokens) replaces them with colors.mint700 / colors.yellow700.
  // This exclusion is removed in PR #13 ("drop pre-existing lint excludes")
  // after PR #4 lands and CI is fully green.
  {
    files: ['src/screens/PracticeScreen.tsx'],
    rules: {
      'no-restricted-syntax': 'off',
    },
  },

  // src/theme.ts is the source of truth for design tokens — hex literals
  // are the literal definition, not a violation.
  {
    files: ['src/theme.ts'],
    rules: {
      'no-restricted-syntax': 'off',
    },
  },

  // Test files: allow direct .ts imports (tsx runtime handles them) and
  // tolerate the deterministic-mock patterns in the test bodies.
  {
    files: ['scripts/**/*.mjs'],
    rules: {
      'import/no-unresolved': 'off',
      // The crisis mock uses bitwise hash; intentional.
      'no-bitwise': 'off',
    },
  },

  // ChatScreen.tsx uses a deterministic char-code hash for the v0 mock
  // responder — the `|` is intentional and not a real bug.
  {
    files: ['src/screens/ChatScreen.tsx'],
    rules: {
      'no-bitwise': 'off',
    },
  },

  // Inline styles are fine in RN — this is a stylistic preference, not
  // a bug. Keep the warning off until a real reviewer pushes for it.
  {
    files: ['**/*.tsx'],
    rules: {
      'react-native/no-inline-styles': 'off',
      // The RootNav tab renderer uses inline arrow components — that's
      // the documented react-navigation pattern and not a re-render trap.
      'react/no-unstable-nested-components': 'off',
    },
  },
];
